export function eventById(id: string) {
  return VARIETY_EVENTS.find((event) => event.id === id) ?? null;
}

export function kindCoverage(events: readonly VarietyEvent[] = VARIETY_EVENTS): Record<VarietyKind, number> {
  const counts: Record<VarietyKind, number> = {
    investigate: 0,
    puzzle: 0,
    escort: 0,
    route: 0,
    repair: 0,
    combat: 0,
  };
  for (const event of events) {
    if (event.investigate) counts.investigate += 1;
    if (event.puzzle) counts.puzzle += 1;
    if (event.escort) counts.escort += 1;
    if (event.routePlan) counts.route += 1;
    if (event.repair) counts.repair += 1;
    if (event.combat) counts.combat += 1;
  }
  return counts;
}
