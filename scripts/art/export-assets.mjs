#!/usr/bin/env node
/**
 * Rebuild every art asset from its editable source.
 *
 *   npm run art:export            # all assets
 *   npm run art:export -- <id>    # one asset
 *
 * For each record in art/assets.json: run the builder registered in
 * art/index.ts, export a GLB with GLTFExporter, embed generated textures,
 * measure the result and write public/game-art/manifest.json.
 * Output is deterministic for a given source, Node and three version.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { embedTexture, inspectGlb, readGlb, writeGlb } from "./lib/glb.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

// GLTFExporter's binary path reads Blobs through FileReader, which Node lacks.
globalThis.FileReader ??= class FileReader {
  readAsArrayBuffer(blob) {
    blob.arrayBuffer().then((result) => {
      this.result = result;
      this.onload?.({ target: this });
      this.onloadend?.({ target: this });
    });
  }
};

export async function exportAsset(record, builders) {
  const { GLTFExporter } = await import("three/examples/jsm/exporters/GLTFExporter.js");
  const build = builders[record.id];
  if (!build) throw new Error(`no builder registered for ${record.id} in art/index.ts`);
  const asset = build();
  asset.scene.updateMatrixWorld(true);
  const exporter = new GLTFExporter();
  const arrayBuffer = await exporter.parseAsync(asset.scene, {
    binary: true,
    animations: asset.clips,
    onlyVisible: false,
  });
  let glb = readGlb(arrayBuffer);
  for (const t of asset.textures) glb = embedTexture(glb, t.material, t.png);
  const bytes = writeGlb(glb);
  return { bytes, meta: asset.meta };
}

export function measure(bytes) {
  const info = inspectGlb(bytes);
  delete info.json;
  delete info.bin;
  return info;
}

async function main() {
  const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
  const registry = JSON.parse(readFileSync(join(ROOT, "art/assets.json"), "utf8"));
  const { ART_BUILDERS } = await import(join(ROOT, "art/index.ts"));
  const manifestPath = join(ROOT, "public/game-art/manifest.json");
  let previous = { assets: [] };
  try {
    previous = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    // First export.
  }
  const out = [];
  for (const record of registry.assets) {
    const kept = previous.assets.find((a) => a.id === record.id);
    if (only.length && !only.includes(record.id)) {
      if (kept) out.push({ ...kept, ...record, metrics: kept.metrics, url: kept.url, meta: kept.meta });
      continue;
    }
    const t0 = performance.now();
    const { bytes, meta } = await exportAsset(record, ART_BUILDERS);
    const file = join(ROOT, record.output);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, bytes);
    const metrics = measure(bytes);
    out.push({
      ...record,
      url: "/" + record.output.replace(/^public\//, ""),
      meta,
      metrics,
    });
    console.log(
      `${record.id}: ${metrics.triangles} tris, ${metrics.vertices} verts, ${(metrics.bytes / 1024).toFixed(1)} KiB, ` +
        `${metrics.animations.length} clips, ${metrics.textures.length} textures (${Math.round(performance.now() - t0)} ms)`,
    );
  }
  const manifest = {
    $comment: "Generated by scripts/art/export-assets.mjs from art/assets.json. Do not edit by hand.",
    schemaVersion: registry.schemaVersion,
    generator: { three: (await import("three")).REVISION, node: process.version },
    assets: out,
  };
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`wrote ${manifestPath}`);
  const runtimePath = join(ROOT, "src/game/art/art-manifest.gen.ts");
  writeFileSync(runtimePath, runtimeManifest(out));
  console.log(`wrote ${runtimePath}`);
}

/** The slim, typed id → url table the game imports. */
export function runtimeManifest(assets) {
  const rows = assets.map((a) => {
    const entry = {
      url: `${a.url}?v=${a.metrics.sha256.slice(0, 12)}`,
      version: a.version,
      sha256: a.metrics.sha256,
      bytes: a.metrics.bytes,
      triangles: a.metrics.triangles,
      animations: a.metrics.animations.map((x) => x.name),
    };
    return `  ${JSON.stringify(a.id)}: ${JSON.stringify(entry)},`;
  });
  return [
    "/* Generated by scripts/art/export-assets.mjs — do not edit by hand. */",
    "export const ART_MANIFEST = {",
    ...rows,
    "} as const;",
    "",
    "export type ArtId = keyof typeof ART_MANIFEST;",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
